def get_arrow_count(grid):
    """计算棋盘中剩余箭头数量"""
    count = 0
    for row in grid:
        for cell in row:
            if cell != EMPTY:
                count += 1
    return count

def is_valid_level(grid):
    """验证关卡是否有解（简单检查：所有箭头都能被消除）"""
    # 这里可以添加更复杂的验证逻辑
    return get_arrow_count(grid) > 0
